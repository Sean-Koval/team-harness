#!/usr/bin/env python3
"""Render the hangar environments that provide a harness's files, from its lock and `bindings/<name>.yaml`.

Until hangar mounts a lock's files itself (hangar#221), the environment provides them, and turn 1 is compared with
the lock (drift). These environments carry exactly the pinned files, so a session thawed from the lock on them
reports the lock's `harness_digest`:

- `env.stable.yaml` (environment `<name>`): the guide, skills, native files and MCP servers; no plugins.
- `env.candidate.yaml` (environment `<name>-candidate`): the same plus the lock's plugin components, loaded from
  hangar's read-only plugin seed (hangar docs/harnesses.md#plugins).

They are written next to the lock because hangar resolves skill and plugin paths inside the spec's directory. Add the
harness directory to hangar's environment directories (`HANGAR_ENV_DIRS`).

    python scripts/render_envs.py harnesses/team-default            # write
    python scripts/render_envs.py harnesses/team-default --check    # CI: exit 1 when out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

HOME_DIRS = {"claude-code": ".claude", "codex": ".codex"}
HEADER = "# Generated by scripts/render_envs.py from harness.lock and bindings/{name}.yaml. Do not edit.\n"


class _Literal(str):
    pass


yaml.SafeDumper.add_representer(_Literal, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def _text(s: str) -> str:
    return _Literal(s) if "\n" in s else s


def render(root: Path) -> dict[str, str]:
    lock = yaml.safe_load((root / "harness.lock").read_text())
    name, runtime = lock["name"], lock["runtime"]["harness"]
    bindings_file = root.parent.parent / "bindings" / f"{name}.yaml"
    bind = yaml.safe_load(bindings_file.read_text()) or {}
    comps = lock["components"]
    home = HOME_DIRS[runtime]

    mcp: dict[str, Any] = {}
    for m in lock["binding"]["mcp"]:
        extra = (bind.get("mcp") or {}).get(m["name"]) or {}
        s: dict[str, Any] = {}
        if m["transport"] == "http":
            s["url"] = m["endpoint"]
            s["headers"] = extra.get("headers") or {}
            if sorted(s["headers"]) != sorted(m.get("header_names") or []):
                raise SystemExit(f"{bindings_file}: mcp.{m['name']}.headers must name exactly {m.get('header_names')}")
        else:
            s["command"] = m["command"]
            s["args"] = list(m.get("args") or [])
            s["env"] = extra.get("env") or {}
            if sorted(s["env"]) != sorted(m.get("env_names") or []):
                raise SystemExit(f"{bindings_file}: mcp.{m['name']}.env must name exactly {m.get('env_names')}")
        for k in ("trust", "write_tools"):
            if k in extra:
                s[k] = extra[k]
        mcp[m["name"]] = s

    guide = next((c for c in comps if c["id"].startswith("guide:")), None)
    files = {f"{home}/{c['path'].split('/', 2)[2]}": _text((root / c["path"]).read_text())
             for c in comps if c["id"].startswith(f"native:{runtime}/")}
    stable: dict[str, Any] = {
        "name": name,
        "description": f"Provides the files of harness {name} (harnesses/{name}/harness.lock) for thaw and experiments",
        "harnesses": [runtime],
        "model": lock["model"]["id"],
        "skills": [{"path": c["path"]} for c in comps if c["id"].startswith("skill:") and c.get("path")],
        "agent_config": {"instructions": _text((root / guide["path"]).read_text()) if guide else None,
                         "files": files},
        "mcp": mcp,
        "secrets": bind.get("secrets") or {},
    }
    if bind.get("dependencies"):
        stable["dependencies"] = bind["dependencies"]
    plugins = [c for c in comps if c["id"].startswith("plugin:")]
    candidate = {"name": f"{name}-candidate", "extends": name,
                 "description": f"{name} with its plugin components loaded from the read-only plugin seed",
                 "plugins": [{"path": ".", "name": c["id"][7:].split("@")[0], "marketplace": c["id"].split("@")[1],
                              "enabled": c.get("enabled", True)} for c in plugins]}
    dump = lambda d: HEADER.format(name=name) + yaml.safe_dump(d, sort_keys=False, width=120, allow_unicode=True)
    out = {"env.stable.yaml": dump(stable)}
    if plugins:
        out["env.candidate.yaml"] = dump(candidate)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("harness", type=Path)
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed files differ")
    a = ap.parse_args()
    want = render(a.harness)
    stale = [f for f in ("env.stable.yaml", "env.candidate.yaml")
             if (a.harness / f).exists() != (f in want) or (f in want and (a.harness / f).read_text() != want[f])]
    if a.check:
        for f in stale:
            print(f"{a.harness / f} is out of date: run scripts/render_envs.py {a.harness}", file=sys.stderr)
        return 1 if stale else 0
    for f in stale:
        if f in want:
            (a.harness / f).write_text(want[f])
        else:
            (a.harness / f).unlink()
        print(f"wrote {a.harness / f}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
