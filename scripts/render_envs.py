#!/usr/bin/env python3
"""Render the hangar environments that provide a harness's files, from its lock and `bindings/<name>.yaml`.

A thawed session mounts the lock's guide, skills and plugins itself (hangar#221); the environment still provides
the native files and the MCP servers, and an experiment variant still names an environment until hangar runs
variants by lock (hangar#135). These environments carry exactly the pinned files, so a session on them reports the
lock's `harness_digest`:

- `env.stable.yaml` (environment `<name>`): the guide, skills, native files and MCP servers of the lock `stable`
  names in `channels.yaml`, read from its release copy (`releases/rN/`, scripts/promote.py) when that isn't the
  current lock, with the bindings of the commit that added that copy; no plugins. A session on the `stable` channel
  thaws that lock and runs the environment's hooks, so they must be the release copy's: after a hook edit on main, a
  stable session keeps the promoted hooks until the next promotion, and turn 1 reports no drift (KAN-477).
- `env.candidate.yaml` (environment `<name>-candidate`): the current lock in full, plugins too (loaded from hangar's
  read-only plugin seed, hangar docs/harnesses.md#plugins), whenever `stable` isn't the current lock or the lock has
  plugins. Sessions on another channel, and flightdeck's environment-based candidate arm, run on it.

Each `settings.json` is provided with `env.HARNESS_NATIVE_DIGEST`: one digest of the harness's other native files (the
hook scripts and whatever they call). hangar's `harness_digest` covers a settings file only by its own bytes (the
hook entries' digest), not the scripts its hooks run, so without this an edited hook would leave the digest, and every
channel that names it, where they were (KAN-473). `relock.py` pins the same text (`native_files`).

They are written next to the lock because hangar resolves skill and plugin paths inside the spec's directory. Add the
harness directory to hangar's environment directories (`HANGAR_ENV_DIRS`).

    python scripts/render_envs.py harnesses/team-default            # write
    python scripts/render_envs.py harnesses/team-default --check    # CI: exit 1 when out of date
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

HOME_DIRS = {"claude-code": ".claude", "codex": ".codex"}
PIN_VAR = "HARNESS_NATIVE_DIGEST"
SETTINGS = "settings.json"
HEADER = "# Generated by scripts/render_envs.py from harness.lock and bindings/{name}.yaml. Do not edit.\n"


class _Literal(str):
    pass


yaml.SafeDumper.add_representer(_Literal, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def _text(s: str) -> str:
    return _Literal(s) if "\n" in s else s


def native_digest(files: dict[str, bytes]) -> str:
    """One digest of {path: content}: each path with the sha256 of its content, in path order."""
    h = hashlib.sha256()
    for path in sorted(files):
        h.update(f"{path}\0{hashlib.sha256(files[path]).hexdigest()}\n".encode())
    return "sha256:" + h.hexdigest()


def native_files(root: Path, runtime: str) -> dict[str, str]:
    """{path under native/<runtime>/: text as the environment provides it}. Every `settings.json` carries
    `env.HARNESS_NATIVE_DIGEST` over the runtime's other native files, so its digest, the one `harness_digest` takes
    for its hooks, changes whenever a hook script does. Other files are provided as they are."""
    base = root / "native" / runtime
    if not base.is_dir():
        return {}
    raw = {p.relative_to(base).as_posix(): p.read_bytes()
           for p in sorted(base.rglob("*")) if p.is_file() and not p.is_symlink()}
    others = {k: v for k, v in raw.items() if k.rsplit("/", 1)[-1] != SETTINGS}
    out: dict[str, str] = {}
    for rel, data in raw.items():
        text = data.decode()
        if rel.rsplit("/", 1)[-1] == SETTINGS:
            doc = json.loads(text)
            env = doc.get("env")
            if others or (isinstance(env, dict) and PIN_VAR in env):  # a frozen copy may carry a stale pin
                env = dict(env) if isinstance(env, dict) else {}
                env.pop(PIN_VAR, None)
                if others:
                    env[PIN_VAR] = native_digest(others)
                doc["env"] = env
                if not env:
                    del doc["env"]
                text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
        out[rel] = text
    return out


def _as_locked(src: Path, lock: dict[str, Any], runtime: str, provided: dict[str, str]) -> dict[str, str]:
    """`provided`, with each settings file as `lock` pinned it: a lock from before KAN-473 (a release copy such as
    team-default r1) pinned its hooks by the settings file's own bytes, without `env.HARNESS_NATIVE_DIGEST`, so the
    copy's file is provided unchanged and a session on it reproduces that lock's digest."""
    home = HOME_DIRS[runtime]
    pinned = {h.get("source"): h.get("digest") for h in lock["binding"].get("hooks") or []}
    out = dict(provided)
    for rel in provided:
        if rel.rsplit("/", 1)[-1] != SETTINGS:
            continue
        raw = (src / "native" / runtime / rel).read_bytes()
        if pinned.get(f"environment:{home}/{rel}") == "sha256:" + hashlib.sha256(raw).hexdigest():
            out[rel] = raw.decode()
    return out


def stable_dir(root: Path) -> Path:
    """The directory of the lock `stable` names: the harness itself when it is the current lock (or the harness has
    no `stable` channel yet), else its release copy. Release copies are found by digest, as hangar's thaw finds them."""
    from hangar import harness_lock as hl

    import promote  # needs hangar too; imported here so native_files needs neither

    lock = yaml.safe_load((root / "harness.lock").read_text(encoding="utf-8"))
    channels = next((p / "channels.yaml" for p in root.resolve().parents if (p / "channels.yaml").is_file()), None)
    chans = ((yaml.safe_load(channels.read_text(encoding="utf-8")) or {}).get(lock["name"]) or {}) if channels else {}
    digest = chans.get("stable")
    if not digest or hl.harness_digest(hl.load(root)) == digest:
        return root
    rel = promote.find_release(root, digest)
    if rel is None:
        raise SystemExit(f"{root}: stable ({digest}) is neither the current lock nor a release copy under "
                         f"{root / promote.RELEASES}/ (scripts/promote.py writes one)")
    return rel


def _git(repo: Path, *args: str) -> str | None:
    try:
        r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=False, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None
    return r.stdout if r.returncode == 0 else None


def _bindings_text(repo: Path, src: Path, root: Path, bindings_file: Path) -> str:
    """The bindings a lock's environment uses. The current lock uses the current bindings/<name>.yaml. A release copy
    uses the bindings as they were in the commit that added it, so a later binding change (a dependency, a secret)
    reaches stable only by promotion, like its files do (KAN-473, KAN-477). A release copy that isn't committed yet
    is being promoted now, from the current bindings."""
    if src.resolve() != root.resolve():
        top = (_git(repo, "rev-parse", "--show-toplevel") or "").strip()
        if top:
            rel = (src / "harness.lock").resolve().relative_to(Path(top).resolve()).as_posix()
            commit = (_git(Path(top), "log", "--diff-filter=A", "--format=%H", "-1", "--", rel) or "").strip()
            if commit:
                b_rel = bindings_file.resolve().relative_to(Path(top).resolve()).as_posix()
                text = _git(Path(top), "show", f"{commit}:{b_rel}")
                if text is None:
                    raise SystemExit(f"{bindings_file}: not in commit {commit[:12]}, which added {rel}")
                return text
    return bindings_file.read_text(encoding="utf-8")


def _environment(root: Path, src: Path, env_name: str, description: str, with_plugins: bool) -> dict[str, Any]:
    """The environment providing the lock in `src` (the harness directory `root` or a release copy under it). Paths
    are relative to `root`, the spec's directory, where hangar resolves them."""
    lock = yaml.safe_load((src / "harness.lock").read_text(encoding="utf-8"))
    name, runtime = lock["name"], lock["runtime"]["harness"]
    # the repository's bindings/, also from a release copy (harnesses/<name>/releases/rN/)
    repo = next((p for p in root.resolve().parents if (p / "bindings").is_dir()), root.parent.parent)
    bindings_file = repo / "bindings" / f"{name}.yaml"
    bind = yaml.safe_load(_bindings_text(repo, src, root, bindings_file)) or {}
    comps = lock["components"]
    home = HOME_DIRS[runtime]
    prefix = src.resolve().relative_to(root.resolve()).as_posix()
    at = (lambda path: path) if prefix == "." else (lambda path: f"{prefix}/{path}")

    mcp: dict[str, Any] = {}
    for m in lock["binding"]["mcp"]:
        extra = (bind.get("mcp") or {}).get(m["name"]) or {}
        s: dict[str, Any] = {}
        if m["transport"] == "http":
            s["url"] = m["endpoint"]
            s["headers"] = extra.get("headers") or {}
            if sorted(s["headers"]) != sorted(m.get("header_names") or []):
                raise SystemExit(f"{bindings_file}: mcp.{m['name']}.headers must name exactly {m.get('header_names')}")
        else:
            s["command"] = m["command"]
            s["args"] = list(m.get("args") or [])
            s["env"] = extra.get("env") or {}
            if sorted(s["env"]) != sorted(m.get("env_names") or []):
                raise SystemExit(f"{bindings_file}: mcp.{m['name']}.env must name exactly {m.get('env_names')}")
        for k in ("trust", "write_tools"):
            if k in extra:
                s[k] = extra[k]
        mcp[m["name"]] = s

    guide = next((c for c in comps if c["id"].startswith("guide:")), None)
    provided = _as_locked(src, lock, runtime, native_files(src, runtime))
    files = {f"{home}/{c['path'].split('/', 2)[2]}": _text(provided[c["path"].split("/", 2)[2]])
             for c in comps if c["id"].startswith(f"native:{runtime}/")}
    env: dict[str, Any] = {
        "name": env_name,
        "description": description,
        "harnesses": [runtime],
        "model": lock["model"]["id"],
        "skills": [{"path": at(c["path"])} for c in comps if c["id"].startswith("skill:") and c.get("path")],
        "agent_config": {"instructions": _text((src / guide["path"]).read_text(encoding="utf-8")) if guide else None,
                         "files": files},
        "mcp": mcp,
        "secrets": bind.get("secrets") or {},
    }
    if bind.get("dependencies"):
        env["dependencies"] = bind["dependencies"]
    plugins = [c for c in comps if c["id"].startswith("plugin:")] if with_plugins else []
    if plugins:
        env["plugins"] = [{"path": at(f"plugins/{c['id'].split('@')[1]}"), "name": c["id"][7:].split("@")[0],
                           "marketplace": c["id"].split("@")[1], "enabled": c.get("enabled", True)}
                          for c in plugins]
    return env


def render(root: Path) -> dict[str, str]:
    lock = yaml.safe_load((root / "harness.lock").read_text(encoding="utf-8"))
    name = lock["name"]
    src = stable_dir(root)
    where = f"harnesses/{name}/{src.relative_to(root).as_posix()}/harness.lock" if src != root else \
        f"harnesses/{name}/harness.lock"
    rev = yaml.safe_load((src / "harness.lock").read_text(encoding="utf-8"))["revision"]
    stable = _environment(root, src, name, f"Provides the files of harness {name}@stable, r{rev} ({where}), for thaw "
                          "and experiments", with_plugins=False)
    dump = lambda d: HEADER.format(name=name) + yaml.safe_dump(d, sort_keys=False, width=120, allow_unicode=True)
    out = {"env.stable.yaml": dump(stable)}
    if src != root or any(c["id"].startswith("plugin:") for c in lock["components"]):
        out["env.candidate.yaml"] = dump(_environment(
            root, root, f"{name}-candidate", f"Provides the files of harness {name}'s current lock, r{lock['revision']} "
            f"(harnesses/{name}/harness.lock), plugins included, for candidate sessions and experiments",
            with_plugins=True))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("harness", type=Path)
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed files differ")
    a = ap.parse_args()
    want = render(a.harness)
    stale = [f for f in ("env.stable.yaml", "env.candidate.yaml")
             if (a.harness / f).exists() != (f in want)
             or (f in want and (a.harness / f).read_text(encoding="utf-8") != want[f])]
    if a.check:
        for f in stale:
            print(f"{a.harness / f} is out of date: run scripts/render_envs.py {a.harness}", file=sys.stderr)
        return 1 if stale else 0
    for f in stale:
        if f in want:
            (a.harness / f).write_text(want[f], encoding="utf-8", newline="\n")
        else:
            (a.harness / f).unlink()
        print(f"wrote {a.harness / f}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
